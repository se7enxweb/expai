    /** @return string[] table names */
    public static function tables()
    {
        return array_keys( self::definition() );
    }

    /** @return string the share/db_schema.dba file content */
    public static function dbaText()
    {
        $schema = self::definition();
        ksort( $schema );
        $schema['_info'] = array( 'format' => 'generic' );
        return "<?php\n"
             . "// The database schema of expai (Exponential Intelligence): generated from expAiSchema::definition() by\n"
             . "// extension/expai/bin/php/expaischema.php --write-files. Do not edit by hand.\n"
             . '$schema = ' . var_export( $schema, true ) . ";\n\n?>\n";
    }

    /**
     * The schema handler for an engine (mysql, postgresql, sqlite, oracle, mongodb).
     * @return eZDBSchemaInterface|null
     */
    public static function handler( $engine, array $schema, $db = null )
    {
        $classes = array( 'mysql' => 'eZMysqlSchema', 'postgresql' => 'eZPgsqlSchema', 'sqlite' => 'eZSQLiteSchema',
                          'oracle' => 'eZOracleSchema', 'mongodb' => 'expMongoSchema' );
        if ( !isset( $classes[$engine] ) )
            return null;
        $class = $classes[$engine];
        if ( !class_exists( $class ) && $engine === 'oracle' )
        {
            $file = eZExtension::baseDirectory() . '/ezoracle/ezdb/dbms-schema/ezoracleschema.php';
            if ( is_file( $file ) )
                require_once $file;
        }
        if ( !class_exists( $class ) )
            return null;
        return new $class( array( 'schema' => $schema, 'instance' => $db, 'type' => $engine ) );
    }

    /** @return string[] SQL statements of the engine for the given tables (all when empty) */
    public static function sqlStatements( $engine, array $tables = array() )
    {
        $schema = self::definition();
        $handler = self::handler( $engine, $schema );
        if ( !$handler )
            return array();
        $local = $schema;
        $local['_info'] = array( 'format' => 'generic' );
        $handler->transformSchema( $local, true );
        unset( $local['_info'] );
        $out = array();
        foreach ( $local as $table => $def )
        {
            if ( $tables && !in_array( $table, $tables, true ) )
                continue;
            foreach ( $handler->generateTableSQLList( $table, $def, array( 'format' => 'local', 'table_type' => $engine === 'mysql' ? 'innodb' : '' ), false ) as $statement )
            {
                $statement = trim( $statement );
                // PL/SQL blocks (Oracle sequences and triggers) end in "END;", which belongs to them
                if ( !preg_match( '/^(BEGIN\b|CREATE OR REPLACE TRIGGER\b)/i', $statement ) )
                    $statement = rtrim( $statement, ';' );
                if ( $statement !== '' )
                    $out[] = $statement;
            }
        }
        return $out;
    }

    /** @return string engine name of a database connection */
    public static function engineOf( eZDBInterface $db )
    {
        $name = strtolower( (string) $db->databaseName() );
        if ( $name === 'postgresql' || $name === 'pgsql' )
            return 'postgresql';
        if ( strpos( $name, 'sqlite' ) === 0 )
            return 'sqlite';
        if ( strpos( $name, 'mongo' ) === 0 )
            return 'mongodb';
        return in_array( $name, array( 'mysql', 'oracle' ), true ) ? $name : $name;
    }

    /** @return string[] the expai tables missing in the database */
    public static function missingTables( $db = null )
    {
        $db = $db ?: eZDB::instance();
        return array_values( array_diff( self::tables(), self::existingTables( $db ) ) );
    }

    /**
     * The expai tables that exist. eZTableList() of the drivers lists only tables named ez*, so each engine is
     * asked directly.
     * @return string[]
     */
    public static function databaseTables( $db = null )
    {
        $db = $db ?: eZDB::instance();
        $engine = self::engineOf( $db );
        if ( $engine === 'mongodb' && method_exists( $db, 'listCollectionNames' ) )
            $names = $db->listCollectionNames();
        else
        {
            switch ( $engine )
            {
                case 'sqlite':
                    $sql = "SELECT name FROM sqlite_master WHERE type='table' AND name LIKE 'expai%'";
                    break;
                case 'mysql':
                    $sql = "SELECT table_name AS name FROM information_schema.tables WHERE table_schema = DATABASE() AND table_name LIKE 'expai%'";
                    break;
                case 'postgresql':
                    $sql = "SELECT relname AS name FROM pg_class WHERE relkind = 'r' AND relname LIKE 'expai%'";
                    break;
                case 'oracle':
                    $sql = "SELECT LOWER(table_name) AS name FROM user_tables WHERE table_name LIKE 'EXPAI%'";
                    break;
                default:
                    return array_map( 'strtolower', array_keys( $db->eZTableList() ) );
            }
            $names = array();
            foreach ( (array) $db->arrayQuery( $sql ) as $row )
            {
                $row = array_change_key_case( $row, CASE_LOWER );
                $names[] = isset( $row['name'] ) ? $row['name'] : reset( $row );
            }
        }
        return array_values( array_unique( array_map( 'strtolower', (array) $names ) ) );
    }

    /**
     * The expai tables of the definition that exist.
     * @return string[]
     */
    public static function existingTables( $db = null )
    {
        return array_values( array_intersect( self::tables(), self::databaseTables( $db ) ) );
    }

    /**
     * Drops the tables of REMOVED_TABLES that still exist (idempotent): expai_package, the record of expai's own
     * package view, removed in 0.0.1.0 (content packages are the kernel's: Setup > Packages, ezpm).
     * @return array( string[] dropped, string[] errors )
     */
    public static function dropRemoved( $db = null )
    {
        $db = $db ?: eZDB::instance();
        $engine = self::engineOf( $db );
        $dropped = array();
        $errors = array();
        foreach ( array_intersect( self::REMOVED_TABLES, self::databaseTables( $db ) ) as $table )
        {
            if ( $engine === 'mongodb' )
            {
                if ( method_exists( $db, 'dropCollection' ) && $db->dropCollection( $table ) !== false )
                    $dropped[] = $table;
                else
                    $errors[] = "mongodb: could not drop $table";
                continue;
            }
            if ( $db->query( "DROP TABLE $table" ) === false )
            {
                $errors[] = "$engine: DROP TABLE $table";
                continue;
            }
            // the sequences of the auto increment id
            if ( $engine === 'postgresql' )
                $db->query( "DROP SEQUENCE IF EXISTS {$table}_id_seq" );
            if ( $engine === 'oracle' )
                $db->query( "BEGIN EXECUTE IMMEDIATE 'DROP SEQUENCE se_$table'; EXCEPTION WHEN OTHERS THEN NULL; END;" );
            $dropped[] = $table;
        }
        return array( $dropped, $errors );
    }

    /**
     * The columns of an expai table in the database.
     * @return string[]|null lower-case names, null when the engine cannot tell (MongoDB: no fixed columns)
     */
    public static function existingColumns( $table, $db = null )
    {
        $db = $db ?: eZDB::instance();
        $engine = self::engineOf( $db );
        $table = preg_replace( '/[^a-z_]/', '', (string) $table );
        switch ( $engine )
        {
            case 'sqlite':
                $rows = $db->arrayQuery( "PRAGMA table_info($table)" );
                $key = 'name';
                break;
            case 'mysql':
                $rows = $db->arrayQuery( "SELECT column_name AS name FROM information_schema.columns WHERE table_schema = DATABASE() AND table_name = '$table'" );
                $key = 'name';
                break;
            case 'postgresql':
                $rows = $db->arrayQuery( "SELECT column_name AS name FROM information_schema.columns WHERE table_name = '$table'" );
                $key = 'name';
                break;
            case 'oracle':
                $rows = $db->arrayQuery( "SELECT LOWER(column_name) AS name FROM user_tab_columns WHERE table_name = '" . strtoupper( $table ) . "'" );
                $key = 'name';
                break;
            default:
                return null;
        }
        $out = array();
        foreach ( (array) $rows as $row )
        {
            $row = array_change_key_case( $row, CASE_LOWER );
            if ( isset( $row[$key] ) )
                $out[] = strtolower( (string) $row[$key] );
        }
        return $out;
    }

    /** how long a missing column is believed missing before it is asked again (an upgrade while processes run) */
    const COLUMN_RECHECK_SECONDS = 300;

    /** @var array "table:col,col" => array( bool have, int recheck after (0: never again) ) */
    protected static $columnChecks = array();

    /** @var array table => array( string[]|null columns, int asked at ): one lookup serves every check of a table for a while */
    protected static $tableColumns = array();

    /**
     * Has a table these columns? Asked once per process: a positive answer is kept for good, a negative one (an
     * installation not upgraded with expaischema.php --install) is asked again after COLUMN_RECHECK_SECONDS, so the
     * upgrade takes effect without restarting long-running workers. An engine that cannot tell (MongoDB), a failed
     * lookup or an empty column list count as present (the statements then behave as before).
     * @param string[] $columns lower-case names
     * @param callable|null $lister function( string $table ): string[]|null (default existingColumns())
     * @param int|null $now the current time (tests)
     * @return bool
     */
    public static function hasColumns( $table, array $columns, $lister = null, $now = null )
    {
        $now = $now === null ? time() : (int) $now;
        $key = (string) $table . ':' . implode( ',', $columns );
        if ( isset( self::$columnChecks[$key] ) && ( self::$columnChecks[$key][1] === 0 || self::$columnChecks[$key][1] > $now ) )
            return self::$columnChecks[$key][0];
        // the columns of the table were looked up a moment ago (for another set of columns): not asked again
        if ( isset( self::$tableColumns[(string) $table] ) && $now - self::$tableColumns[(string) $table][1] >= 0
             && $now - self::$tableColumns[(string) $table][1] < self::COLUMN_RECHECK_SECONDS )
            $have = self::$tableColumns[(string) $table][0];
        else
        {
            try
            {
                $have = $lister ? call_user_func( $lister, (string) $table ) : self::existingColumns( $table );
            }
            catch ( Exception $e )
            {
                $have = null;
            }
            self::$tableColumns[(string) $table] = array( $have, $now );
        }
        if ( !is_array( $have ) || !$have )
        {
            // unknown: taken as present, asked again later
            self::$columnChecks[$key] = array( true, $now + self::COLUMN_RECHECK_SECONDS );
            return true;
        }
        $ok = !array_diff( $columns, $have );
        self::$columnChecks[$key] = array( $ok, $ok ? 0 : $now + self::COLUMN_RECHECK_SECONDS );
        return $ok;
    }

    /** Forgets what hasColumns() learned (tests, after --install in the same process) */
    public static function forgetColumns()
    {
        self::$columnChecks = array();
        self::$tableColumns = array();
    }

    /** @return string[] the index names of an expai table in the database (lower case), null when unknown */
    public static function existingIndexes( $table, $db = null )
    {
        $db = $db ?: eZDB::instance();
        $table = preg_replace( '/[^a-z_]/', '', (string) $table );
        switch ( self::engineOf( $db ) )
        {
            case 'sqlite':
                $sql = "SELECT name FROM sqlite_master WHERE type = 'index' AND tbl_name = '$table'";
                break;
            case 'mysql':
                $sql = "SELECT DISTINCT index_name AS name FROM information_schema.statistics WHERE table_schema = DATABASE() AND table_name = '$table'";
                break;
            case 'postgresql':
                $sql = "SELECT indexname AS name FROM pg_indexes WHERE tablename = '$table'";
                break;
            case 'oracle':
                $sql = "SELECT LOWER(index_name) AS name FROM user_indexes WHERE table_name = '" . strtoupper( $table ) . "'";
                break;
            default:
                return null;
        }
        $out = array();
        foreach ( (array) $db->arrayQuery( $sql ) as $row )
        {
            $row = array_change_key_case( $row, CASE_LOWER );
            $out[] = strtolower( (string) $row['name'] );
        }
        return $out;
    }

    /**
     * The columns and indexes of the existing expai tables that the database lacks (an installation of an earlier
     * state of expai).
     * @return array list of "table.column" and "table index name"
     */
    public static function missingColumns( $db = null )
    {
        $db = $db ?: eZDB::instance();
        $out = array();
        $existing = self::existingTables( $db );
        foreach ( self::definition() as $table => $def )
        {
            if ( !in_array( $table, $existing, true ) )
                continue;
            $columns = self::existingColumns( $table, $db );
            if ( $columns !== null )
                foreach ( array_keys( $def['fields'] ) as $field )
                    if ( !in_array( $field, $columns, true ) )
                        $out[] = "$table.$field";
            $indexes = self::existingIndexes( $table, $db );
            if ( $indexes !== null )
                foreach ( $def['indexes'] as $name => $index )
                    if ( $name !== 'PRIMARY' && !in_array( strtolower( $name ), $indexes, true ) )
                        $out[] = "$table index $name";
        }
        return $out;
    }

    /**
     * The statements that add the missing columns and indexes (ALTER TABLE ADD ..., CREATE INDEX ...), generated by
     * the engine's schema handler.
     * @return string[]
     */
    public static function upgradeStatements( $db = null )
    {
        $db = $db ?: eZDB::instance();
        $engine = self::engineOf( $db );
        $schema = self::definition();
        $handler = self::handler( $engine, $schema );
        if ( !$handler )
            return array();
        $local = $schema;
        $local['_info'] = array( 'format' => 'generic' );
        $handler->transformSchema( $local, true );
        $statements = array();
        foreach ( self::missingColumns( $db ) as $missing )
        {
            if ( preg_match( '/^(\w+)\.(\w+)$/', $missing, $m ) )
                $sql = $handler->generateAddFieldSql( $m[1], $m[2], $local[$m[1]]['fields'][$m[2]], array( 'format' => 'local' ) );
            elseif ( preg_match( '/^(\w+) index (\w+)$/', $missing, $m ) )
                $sql = $handler->generateAddIndexSql( $m[1], $m[2], $local[$m[1]]['indexes'][$m[2]], array( 'format' => 'local' ) );
            else
                continue;
            foreach ( preg_split( '/;\s*\n/', (string) $sql ) as $statement )
                if ( trim( $statement ) !== '' )
                    $statements[] = rtrim( trim( $statement ), ';' );
        }
        return $statements;
    }

    /**
     * The bigint columns of the definition (table => column list): an installation of an earlier state has int there.
     * @return array
     */
    public static function bigintColumns()
    {
        $out = array();
        foreach ( self::definition() as $table => $def )
            foreach ( $def['fields'] as $field => $column )
                if ( isset( $column['type'] ) && $column['type'] === 'bigint' )
                    $out[$table][] = $field;
        return $out;
    }

    /**
     * The statements that widen int columns of an earlier state to bigint (the *_micros columns). SQLite stores
     * every integer in 64 bits and Oracle's INTEGER is NUMBER(38): nothing to do there.
     * @param array|null $types table => array( column => the column's type in the database, lower case ); null: asked
     * @return string[]
     */
    public static function widenStatements( $db = null, $types = null )
    {
        $db = $db ?: eZDB::instance();
        $engine = self::engineOf( $db );
        if ( !in_array( $engine, array( 'mysql', 'postgresql' ), true ) )
            return array();
        $existing = $types === null ? self::existingTables( $db ) : array_keys( $types );
        $statements = array();
        foreach ( self::bigintColumns() as $table => $columns )
        {
            if ( !in_array( $table, $existing, true ) )
                continue;
            $have = $types === null ? self::columnTypes( $table, $db ) : $types[$table];
            foreach ( $columns as $column )
            {
                // a column that is missing is added as bigint by upgradeStatements()
                if ( !isset( $have[$column] ) || strpos( $have[$column], 'bigint' ) === 0 )
                    continue;
                $statements[] = $engine === 'mysql'
                    ? "ALTER TABLE $table MODIFY $column bigint(20) NOT NULL DEFAULT '0'"
                    : "ALTER TABLE $table ALTER COLUMN $column TYPE bigint";
            }
        }
        return $statements;
    }

    /** @return array column => type (lower case) of a table in a MySQL or PostgreSQL database */
    public static function columnTypes( $table, $db = null )
    {
        $db = $db ?: eZDB::instance();
        $table = preg_replace( '/[^a-z_]/', '', (string) $table );
        $sql = self::engineOf( $db ) === 'mysql'
             ? "SELECT column_name AS name, data_type AS type FROM information_schema.columns WHERE table_schema = DATABASE() AND table_name = '$table'"
             : "SELECT column_name AS name, data_type AS type FROM information_schema.columns WHERE table_name = '$table'";
        $out = array();
        foreach ( (array) $db->arrayQuery( $sql ) as $row )
        {
            $row = array_change_key_case( $row, CASE_LOWER );
            $out[strtolower( (string) $row['name'] )] = strtolower( (string) $row['type'] );
        }
        return $out;
    }

    /**
     * Creates the missing expai tables in the database (idempotent).
     * @return array( string[] created, string[] errors )
     */
    public static function ensure( $db = null )
    {
        $db = $db ?: eZDB::instance();
        $missing = self::missingTables( $db );
        $engine = self::engineOf( $db );
        $created = array();
        $errors = array();
        // the tables of earlier versions (REMOVED_TABLES)
        list( $dropped, $dropErrors ) = self::dropRemoved( $db );
        foreach ( $dropped as $table )
            $created[] = 'dropped: ' . $table;
        $errors = array_merge( $errors, $dropErrors );
        // the columns and indexes an earlier state lacks
        if ( $engine !== 'mongodb' )
            foreach ( self::upgradeStatements( $db ) as $statement )
            {
                if ( $db->query( $statement ) === false )
                    $errors[] = $engine . ': ' . substr( $statement, 0, 120 );
                else
                    $created[] = 'upgrade: ' . substr( $statement, 0, 120 );
            }
        // the int columns of an earlier state that are bigint now
        foreach ( self::widenStatements( $db ) as $statement )
        {
            if ( $db->query( $statement ) === false )
                $errors[] = $engine . ': ' . substr( $statement, 0, 120 );
            else
                $created[] = 'upgrade: ' . substr( $statement, 0, 120 );
        }
        // what the tables lacked is asked again after the upgrade (hasColumns())
        self::forgetColumns();
        if ( !$missing )
            return array( $created, $errors );
        if ( $engine === 'mongodb' )
        {
            $schema = array_intersect_key( self::definition(), array_flip( $missing ) );
            $handler = self::handler( 'mongodb', $schema, $db );
            if ( $handler && method_exists( $handler, 'insertSchema' ) && $handler->insertSchema( array( 'schema' => true, 'data' => false ) ) )
                $created = array_merge( $created, $missing );
            else
                $errors[] = 'mongodb: the schema handler could not create ' . implode( ', ', $missing );
            return array( $created, $errors );
        }
        $statements = self::sqlStatements( $engine, $missing );
        if ( !$statements )
            return array( array(), array( "no schema handler for the engine $engine" ) );
        foreach ( $statements as $statement )
        {
            if ( $db->query( $statement ) === false )
                $errors[] = $engine . ': ' . substr( $statement, 0, 80 );
        }
        $remaining = self::missingTables( $db );
        return array( array_merge( $created, array_values( array_diff( $missing, $remaining ) ) ), $errors );
    }
